/**
 * 描画層の唯一の公開インタフェース（docs/06 §6.2）。
 *
 * D9 で Three.js のネイティブ WebGPU splat レンダラ (r186+) を選んだが、
 * 調査時点の npm 最新 three@0.185.1 には splat モジュールが含まれていない。
 * そこでこの薄い抽象を1枚挟み、まず自前 WGSL 実装で進めて r186 が出たら
 * 差し替えられるようにする。両方を維持し続けることはしない。
 */

/** レンダラが消費するスプラットの GPU 表現。1個 24 バイト（docs/04 §4.8.1）。 */
export const SPLAT_BYTES = 24;

/**
 * サーフェルの厚み ÷ 面内の半径（v2.6.3、docs/06 §6.11）。
 *
 * **0 にしてはいけない。** 厚みの無い円板は、視線に対して寝ると画面上で
 * 線に潰れる。実測（実写、私たちのビューアの式）で射影後の細長さ
 * （長軸 ÷ 短軸）は 90% で 12.9、99% で 3.3×10⁶ になっていた。顔や体に
 * 並ぶ斜めの縞の正体がこれである（docs/09 §V15）。
 *
 * 値は参照実装（SHARP）の出力から採った。あちらは大きさ帯によらず
 * 小軸 ÷ 大軸 が 0.33〜0.45 で一定である。同じ実写で射影後の細長さは:
 *
 * | | 50% | 90% | 99% |
 * |---|---|---|---|
 * | 参照実装 | 1.34 | 1.99 | 3.54 |
 * | 厚み 0（v2.6.2 まで） | 2.01 | **12.86** | **3.3×10⁶** |
 * | 厚み = 半径 × 0.35 | 1.73 | 2.88 | 2.94 |
 *
 * 面内の半径に**比例**させる。定数にすると、大きいスプラットだけが
 * 極端に平たくなる（書き出しの `.splat` がそうなっていた。半径 0.005 の
 * スプラットで比 0.067）。
 *
 * この値はシェーダ（`splat.wgsl` / `splat.vert`）と書き出しの両方に
 * 現れる。ずれると自前ビューアと外部ビューアで形が変わるので、
 * `tests/unit/exportSplats.test.ts` が一致を機械的に確かめる。
 */
export const SURFEL_FLATNESS = 0.35;

export interface ViewState {
  /** 被写体中心からの方位角（ラジアン）。 */
  yaw: number;
  /** 仰角（ラジアン）。 */
  pitch: number;
  /** 被写体までの距離。1.0 が生成時のカメラ位置。 */
  distance: number;
  /** 注視点のずらし（パン）。 */
  target: [number, number, number];
}

export interface RenderStats {
  /** 直近フレームで実際に描画されたスプラット数（背面カリング後）。 */
  drawnSplats: number;
  /** 直近フレームの CPU 側実測時間（ミリ秒）。 */
  frameMs: number;
  /** LOD の間引き段（1 = 間引きなし）。 */
  lodStride: number;
}

export interface SplatRenderer {
  /** 描画対象を差し替える。プレビュー確定時と微調整完了時に呼ばれる。 */
  setSplats(data: ArrayBufferView, count: number): void;
  setCamera(view: ViewState): void;
  render(): void;
  /**
   * 直前の render() の GPU 側の完了を待つ。
   *
   * ベンチで正確な時間を測るために要る。通常の描画ループでは呼ばない
   * （待つとパイプラインが止まって遅くなる）。待ち方はバックエンドで違う。
   */
  flush(): Promise<void>;
  /**
   * 直前の `render()` が出したピクセルを RGBA8 で読み戻す（左上原点）。
   *
   * 検証専用。フレーム時間や drawnSplats はレンダラの自己申告なので、
   * 「真っ黒を高速に描く」バグはそれでは見つからない。
   * キャンバスを 2D に drawImage する手は WebGPU では使えない（実測で
   * 常に空になった）ので、バックエンドごとの正規の経路で読む。
   */
  readPixels(): Promise<Uint8Array>;
  resize(width: number, height: number): void;
  dispose(): void;
  readonly stats: RenderStats;
}

/**
 * 正規化された被写体を包む球の半径（docs/06 §6.5）。
 *
 * ⑥ は被写体を**一辺 1 の立方体**に収めて出す（`6-splats.ts` の `extent`）。
 * その半対角は √3/2 = 0.866 なので、少し余裕を見て 0.9 とする。
 *
 * **深度ソートのバケットはこの半径で張る。** カメラからの距離 d に対して
 * [d − R, d + R] を 8192 等分すれば、どの距離でも被写体全体が入る。
 * v2.6.7 まではここに「生成時のカメラ（距離 1.0）から見た深度レンジ」を
 * 使っていて、**距離 1.0 以外では全部が 1 バケットに潰れていた**
 * （実測: 距離 0.6 以下・1.4 以上で 8192 個中 1 個しか使われない）。
 * ソートが効かないと α 合成の順序が乱れ、奥の面が手前に出て**透けて**見える。
 * docs/09 §V22。
 */
export const SCENE_RADIUS = 0.9;

/** 単位立方体に正規化された被写体を見るカメラの既定値。 */
export function defaultView(): ViewState {
  return { yaw: 0, pitch: 0, distance: 1.0, target: [0, 0, 0] };
}
